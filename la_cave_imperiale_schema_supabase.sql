-- ---------- Helpers ----------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  nom text,
  prenoms text,
  telephone text,
  role public.app_role not null default 'vendeur',
  actif boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer
set search_path = public as $$
begin
  insert into public.profiles(id,email,nom,prenoms)
  values(new.id, lower(new.email), new.raw_user_meta_data->>'nom',
         new.raw_user_meta_data->>'prenoms')
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created_cave on auth.users;
create trigger on_auth_user_created_cave after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.current_role()
returns public.app_role language sql stable security definer
set search_path = public as $$
  select role from public.profiles where id = auth.uid() and actif = true
$$;

create or replace function public.is_staff()
returns boolean language sql stable security definer
set search_path = public as $$
  select exists(select 1 from public.profiles
                where id=auth.uid() and actif=true)
$$;

create or replace function public.is_manager()
returns boolean language sql stable security definer
set search_path = public as $$
  select exists(select 1 from public.profiles
    where id=auth.uid() and actif=true
      and role in ('admin','gerant','comptable'))
$$;

