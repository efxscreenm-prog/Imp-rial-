-- Empêche les modifications de mouvements/ventes sur une journée clôturée
-- lorsque l'opération est saisie avec date_mouvement/date_vente correspondante.
create or replace function public.prevent_closed_day_stock()
returns trigger language plpgsql as $$
declare d date;
begin
  d := coalesce(new.date_mouvement::date, old.date_mouvement::date);
  if exists(select 1 from public.daily_closures
            where jour=d and statut='cloturee') then
    raise exception 'Cette journée est clôturée : modification interdite.';
  end if;
  return coalesce(new,old);
end $$;

drop trigger if exists trg_no_stock_after_close on public.stock_movements;
create trigger trg_no_stock_after_close
before insert or update or delete on public.stock_movements
for each row execute function public.prevent_closed_day_stock();

