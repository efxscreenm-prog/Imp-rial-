create or replace view public.v_dashboard_global as
with sales_stats as (
  select
    coalesce(sum(si.montant),0)::numeric(14,2) ca_total,
    coalesce(sum(si.marge),0)::numeric(14,2) marge_totale,
    coalesce(sum(si.montant) filter(where s.date_vente::date=current_date),0)::numeric(14,2) ca_jour,
    coalesce(sum(si.montant) filter(where date_trunc('month',s.date_vente)=date_trunc('month',now())),0)::numeric(14,2) ca_mois
  from public.sales s join public.sale_items si on si.sale_id=s.id
  where s.statut_paiement <> 'annule'
), stock_stats as (
  select count(*) filter(where alerte_stock) nb_alertes,
         coalesce(sum(stock_actuel),0)::numeric(14,3) quantite_stock,
         coalesce(sum(valeur_achat),0)::numeric(14,2) valeur_stock_achat,
         coalesce(sum(valeur_detail),0)::numeric(14,2) valeur_stock_detail,
         count(*) nb_articles
  from public.v_stock_actuel
), debt_stats as (
  select coalesce(sum(montant_initial-montant_regle),0)::numeric(14,2) dettes_clients
  from public.customer_debts where statut='en_cours'
), expense_stats as (
  select coalesce(sum(montant),0)::numeric(14,2) depenses_mois
  from public.cash_expenses
  where date_trunc('month',date_depense)=date_trunc('month',now())
)
select ss.ca_total,ss.ca_jour,ss.ca_mois,ss.marge_totale,
       st.nb_articles,st.nb_alertes,st.quantite_stock,
       st.valeur_stock_achat,st.valeur_stock_detail,
       ds.dettes_clients,es.depenses_mois
from sales_stats ss cross join stock_stats st
cross join debt_stats ds cross join expense_stats es;

create or replace view public.v_dashboard_categories as
select c.id category_id,c.nom categorie,
       coalesce(sum(si.montant),0)::numeric(14,2) chiffre_affaires,
       coalesce(sum(si.marge),0)::numeric(14,2) marge
from public.categories c
left join public.products p on p.category_id=c.id
left join public.sale_items si on si.product_id=p.id
left join public.sales s on s.id=si.sale_id and s.statut_paiement <> 'annule'
group by c.id,c.nom;

create or replace view public.v_dashboard_journalier as
select s.date_vente::date jour,
       coalesce(sum(si.montant),0)::numeric(14,2) chiffre_affaires,
       coalesce(sum(si.marge),0)::numeric(14,2) marge,
       count(distinct s.id) nombre_ventes
from public.sales s
join public.sale_items si on si.sale_id=s.id
where s.statut_paiement <> 'annule'
group by s.date_vente::date
order by jour desc;

