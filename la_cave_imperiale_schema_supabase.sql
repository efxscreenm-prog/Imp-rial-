-- ---------- Grand livre de stock ----------
-- Toutes les variations de stock sont historisées ici.
-- Une entrée = quantité positive ; vente/avarie = quantité négative.
create table if not exists public.stock_movements (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id),
  movement public.movement_type not null,
  quantite numeric(14,3) not null check(quantite <> 0),
  cout_unitaire numeric(14,2) not null default 0 check(cout_unitaire >= 0),
  date_mouvement timestamptz not null default now(),
  purchase_item_id uuid references public.purchase_items(id),
  sale_item_id uuid references public.sale_items(id),
  motif text,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now(),
  check (
    (movement in ('entree','retour') and quantite > 0)
    or (movement in ('vente','avarie') and quantite < 0)
    or movement = 'ajustement'
  )
);

create index if not exists idx_stock_movements_product_date
  on public.stock_movements(product_id,date_mouvement desc);

create or replace view public.v_stock_actuel as
select p.id product_id, p.code, p.designation, p.category_id,
       p.prix_achat, p.prix_gros, p.prix_detail, p.seuil_alerte,
       coalesce(sum(sm.quantite),0)::numeric(14,3) stock_actuel,
       (coalesce(sum(sm.quantite),0) <= p.seuil_alerte) alerte_stock,
       (coalesce(sum(sm.quantite),0) * p.prix_achat)::numeric(14,2) valeur_achat,
       (coalesce(sum(sm.quantite),0) * p.prix_detail)::numeric(14,2) valeur_detail
from public.products p
left join public.stock_movements sm on sm.product_id=p.id
where p.actif=true
group by p.id;

