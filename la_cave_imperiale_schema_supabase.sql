    execute format('create policy %I_write on public.%I for all to authenticated using (public.current_role() in (''admin'',''gerant'',''vendeur'',''magasinier'',''comptable'')) with check (public.current_role() in (''admin'',''gerant'',''vendeur'',''magasinier'',''comptable''))',t,t);
